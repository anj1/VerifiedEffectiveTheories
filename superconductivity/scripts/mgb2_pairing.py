#!/usr/bin/env python3
"""Reproduce the MgB2 static phonon-channel ablations and Lean witnesses."""
import argparse
from fractions import Fraction as Q
from itertools import product
import json
from pathlib import Path

from pairing import eigenvalue_bounds, lean_rat, lean_vec, rational


INPUT = Path(__file__).resolve().parents[1] / "artifacts" / "mgb2_pairing_inputs.json"
GROUPS = ((0, 1), (2, 3))
ABLATIONS = {
    "full": ((True, True), (True, True)),
    "withoutSigma": ((False, True), (True, True)),
    "withoutPi": ((True, True), (True, False)),
    "withoutInterband": ((True, False), (False, True)),
}


def read_matrix(raw, size):
    if len(raw) != size or any(len(row) != size for row in raw):
        raise ValueError(f"expected a {size} by {size} matrix")
    matrix = [list(map(rational, row)) for row in raw]
    if any(value < 0 for row in matrix for value in row):
        raise ValueError("phonon attraction entries must be nonnegative")
    return matrix


def lean_matrix(matrix):
    return lean_vec(lean_vec(map(lean_rat, row)) for row in matrix)


def two_band(matrix):
    return "⟨" + ", ".join(lean_rat(value) for row in matrix for value in row) + "⟩"


def two_band_bounds(matrix):
    # The diagonal metric diag(c, b) symmetrizes the gap matrix.
    (a, b), (c, d) = matrix
    if b * c == 0:
        return max(a, d), max(a, d)
    cert = eigenvalue_bounds([[a * c, b * c], [b * c, d * b]], [c, b], digits=5)
    return cert.lo, cert.hi


def analyze(raw):
    dos = list(map(rational, raw["liu"]["dos_per_ry_spin_cell"]))
    interaction = read_matrix(raw["liu"]["static_interaction_ry"], 4)
    if len(dos) != 4 or min(dos) <= 0:
        raise ValueError("expected four positive sheet densities of states")
    if any(interaction[i][j] != interaction[j][i] for i, j in product(range(4), repeat=2)):
        raise ValueError("the sheet interaction must be symmetric")
    sheet = [[dos[i] * interaction[i][j] * dos[j] for j in range(4)] for i in range(4)]
    liu = [[sum(sheet[i][j] for i, j in product(row, col)) / sum(dos[i] for i in row)
            for col in GROUPS] for row in GROUPS]
    brinkman = read_matrix(raw["brinkman"]["static_coupling"], 2)
    two = {
        source: {
            cut: two_band_bounds([[matrix[i][j] if keep[i][j] else Q(0) for j in range(2)]
                                  for i in range(2)])
            for cut, keep in ABLATIONS.items()
        }
        for source, matrix in (("liu", liu), ("brinkman", brinkman))
    }
    four = {
        cut: eigenvalue_bounds(
            [[sheet[i][j] if keep[i // 2][j // 2] else Q(0) for j in range(4)] for i in range(4)],
            dos, digits=5)
        for cut, keep in ABLATIONS.items()
    }
    padding = rational(raw["static_entry_sensitivity"])
    if padding < 0:
        raise ValueError("the sensitivity allowance must be nonnegative")
    bounds = (padding, min(liu[0][0], brinkman[0][0]) - padding,
              [[max(liu[i][j], brinkman[i][j]) + padding for j in range(2)] for i in range(2)])
    return dos, interaction, brinkman, two, four, bounds


def read_a_point(raw):
    mode_lambdas = list(map(rational, raw["a_point_mode_lambda"]))
    e2g = raw["a_point_e2g_mode_indices"]
    measured = rational(raw["a_point_e2g_xray_lambda"])
    error = rational(raw["a_point_e2g_xray_reported_error"])
    if len(mode_lambdas) != 9 or min(mode_lambdas) < 0 or sum(mode_lambdas) == 0:
        raise ValueError("expected nine nonnegative A-point couplings with a positive sum")
    if (len(e2g) != 2 or any(type(i) is not int or not 0 <= i < 9 for i in e2g)
            or e2g[0] == e2g[1] or not 0 <= error <= measured):
        raise ValueError("invalid A-point E2g doublet or X-ray interval")
    return mode_lambdas, e2g, measured, error


def lean_source(result, a_point):
    dos, interaction, brinkman, two, four, (padding, min_sigma, upper) = result
    lines = [
        "import Grain.PairingAttribution",
        "",
        "/- Generated by scripts/mgb2_pairing.py --lean from artifacts/mgb2_pairing_inputs.json. -/",
        "",
        "namespace Grain.Pairing.Attribution.MgB2",
        "",
        f"def dos : Fin 4 → ℚ := {lean_vec(map(lean_rat, dos))}",
        f"def interaction : Fin 4 → Fin 4 → ℚ := {lean_matrix(interaction)}",
        "def sigma : Finset (Fin 4) := {0, 1}",
        "def piBand : Finset (Fin 4) := {2, 3}",
        "def liu : Coupling := Coupling.block dos interaction sigma piBand",
        f"def brinkman : Coupling := {two_band(brinkman)}",
        f"def sensitivity : ℚ := {lean_rat(padding)}",
        f"def minSigma : ℚ := {lean_rat(min_sigma)}",
        f"def upper : Coupling := {two_band(upper)}",
        "",
        "def retain (cut : Fin 2 → Fin 2 → Bool) (i j : Fin 4) : ℚ :=",
        "  if cut (if i ∈ sigma then 0 else 1) (if j ∈ sigma then 0 else 1)",
        "    then sheetKernel dos interaction i j else 0",
        "",
    ]
    suffix = dict(full="", withoutSigma=".withoutFirst", withoutPi=".withoutSecond",
                  withoutInterband=".withoutInterband")
    for source, channels in two.items():
        for cut, endpoints in channels.items():
            lo, hi = map(lean_rat, endpoints)
            k = source + suffix[cut]
            lines.extend([
                f"theorem {source}_{cut} :",
                f"    (({lo} : ℚ) : ℝ) ≤ {k}.leading ∧ {k}.leading ≤ (({hi} : ℚ) : ℝ) :=",
                f"  Coupling.leading_bounds {k} ({lo}) ({hi})",
                "    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)",
                "",
            ])
    for cut, cert in four.items():
        keep = lean_vec(lean_vec(str(value).lower() for value in row) for row in ABLATIONS[cut])
        lo, hi = lean_rat(cert.lo), lean_rat(cert.hi)
        trial = lean_vec(map(lean_rat, cert.trial))
        pivots = lean_vec(map(lean_rat, cert.pivots))
        lines.extend([
            f"def sheet_{cut} := retain {keep}",
            f"theorem sheet_{cut}_bounds :",
            f"    (({lo} : ℚ) : ℝ) ≤ Pairing.leading sheet_{cut} dos ∧",
            f"    Pairing.leading sheet_{cut} dos ≤ (({hi} : ℚ) : ℝ) := by",
            f"  exact eigenvalue_bounds sheet_{cut} dos ({lo}) ({hi})",
            f"    {trial}",
            f"    {lean_matrix(cert.lower)}",
            f"    {pivots}",
            "    (by decide +kernel) (by decide +kernel)",
            "",
        ])
    upper_cut = [row.copy() for row in upper]
    upper_cut[0][0] = Q(0)
    mode_lambdas, e2g, measured, error = a_point
    lines.extend([
        "theorem upper_withoutSigma :",
        f"    upper.withoutFirst.leading ≤ (({lean_rat(two_band_bounds(upper_cut)[1])} : ℚ) : ℝ) :=",
        f"  (Coupling.leading_bounds upper.withoutFirst 0 ({lean_rat(two_band_bounds(upper_cut)[1])})",
        "    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)).2",
        "",
        f"def aPointMode : Fin 9 → ℚ := {lean_vec(map(lean_rat, mode_lambdas))}",
        f"def aPointE2g : Finset (Fin 9) := {{{', '.join(map(str, e2g))}}}",
        f"def xrayCenter : ℚ := {lean_rat(measured)}",
        f"def xrayError : ℚ := {lean_rat(error)}",
        "",
        "end Grain.Pairing.Attribution.MgB2",
    ])
    return "\n".join(lines) + "\n"


def report(result, a_point):
    _, _, _, two, four, (padding, _, _) = result
    spectra = {**two, "liuFourSheet": {cut: (v.lo, v.hi) for cut, v in four.items()}}
    mode_lambdas, e2g, measured, error = a_point
    total = sum(mode_lambdas)
    doublet = sum(mode_lambdas[i] for i in e2g)
    return {
        "static_entry_sensitivity": str(padding),
        "leading_eigenvalue": {
            source: {cut: list(map(str, interval)) for cut, interval in cuts.items()}
            for source, cuts in spectra.items()
        },
        "a_point": {
            "lambda_total": str(total),
            "lambda_e2g": str(doublet),
            "e2g_share": str(doublet / total),
            "xray_lambda_interval_per_component": [str(measured - error), str(measured + error)],
        },
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean", action="store_true", help="emit the Lean certificate")
    args = parser.parse_args()
    try:
        raw = json.loads(INPUT.read_text(), parse_float=Q)
        result = analyze(raw)
        a_point = read_a_point(raw["shukla"])
        if args.lean:
            print(lean_source(result, a_point), end="")
        else:
            print(json.dumps(report(result, a_point), indent=2))
    except (KeyError, TypeError, ValueError, OSError, ArithmeticError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
