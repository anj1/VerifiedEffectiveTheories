#!/usr/bin/env python3
"""Reproduce the four-site channel certificates checked by Lean."""
import argparse
from fractions import Fraction
from itertools import product
from pathlib import Path

from crystal_bcs import read_crystal
from fermion import apply
from four_site_eft import difference
from thermal_bounds import free_energy, trace_bounds

ROOT = Path(__file__).resolve().parents[1]
DIMENSION = 256
TEMPERATURES = ((8, 96), (20, 56))
RESPONSE_GRID = 10**6


def signed_columns(crystal, mask, field):
    terms = []
    for q, k, p in product(range(4), repeat=3):
        channel = 0 if k == p else 1 if k ^ p == q else 2
        if q == 0 or mask & (1 << channel):
            terms.append((-40 * crystal.coupling,
                          ((True, 2*k), (True, 2*(q^k)+1),
                           (False, 2*(q^p)+1), (False, 2*p))))
    if field:
        for k in range(4):
            terms.extend([(-2, ((True, 2*k), (True, 2*k+1))),
                          (-2, ((False, 2*k+1), (False, 2*k)))])
    columns = []
    for state in range(DIMENSION):
        kinetic = sum(40 * crystal.xi[k] * ((state >> (2*k) & 3).bit_count())
                      for k in range(4))
        column = [(state, kinetic)]
        for coefficient, operators in terms:
            result = apply(state, operators)
            if result is not None:
                other, sign = result
                column.append((other, coefficient * sign))
        if any(Fraction(v).denominator != 1 for _, v in column):
            raise ValueError("the certificate requires integer scaled matrix entries")
        columns.append([(i, int(v)) for i, v in column])
    return columns


def blocks_from_columns(columns):
    remaining = set(range(DIMENSION))
    while remaining:
        root = min(remaining)
        remaining.remove(root)
        pending = [root]
        for j in pending:
            for i, _ in columns[j]:
                if i in remaining:
                    pending.append(i)
                    remaining.remove(i)
        states = sorted(pending)
        index = {i: j for j, i in enumerate(states)}
        yield states, [[(index[i], -v) for i, v in columns[j]] for j in states]


def taylor_diagonal(block, divisor, degree, checkpoints=None):
    for root in range(len(block)):
        v = [int(i == root) for i in range(len(block))]
        contribution = 1
        scale = 1
        for k in range(1, degree + 1):
            v = [sum(value*v[i] for i, value in column) for column in block]
            ratio = divisor*k
            contribution = ratio*contribution + v[root]
            scale *= ratio
            if checkpoints is not None and k % 24 == 0 and k < degree:
                checkpoints[root].append((k, v, contribution, scale))
        yield contribution


def lean_list(items):
    return "[" + ", ".join(map(str, items)) + "]"


def lean_block(states, columns):
    rows = (lean_list(f"({i}, {v})" for i, v in column) for column in columns)
    return ("  { states := " + lean_list(states) + ", columns :=\n    [" +
            ",\n     ".join(rows) + "] }")


def matrix_from_columns(columns):
    result = [{} for _ in columns]
    for j, column in enumerate(columns):
        for i, value in column:
            result[i][j] = result[i].get(j, 0) + Fraction(value, 40)
            if not result[i][j]:
                del result[i][j]
    return result


def lean_sources(crystal):
    preamble = [
        "/- Generated by scripts/hubbard_channels.py. All witnesses are checked in Lean. -/",
        "import Grain.HubbardTrace", "", "namespace Grain.HubbardChannels", "",
        "set_option Elab.async false", "set_option maxRecDepth 100000", "set_option maxHeartbeats 0", "",
    ]
    for mask in range(8):
        lines = preamble.copy()
        if mask != 0:
            lines[1] = "import Grain.HubbardSteps"
        response_data = [[None, None] for _ in TEMPERATURES]
        for field in (0, 1):
            name = f"m{mask}h{field}"
            flag = "true" if field else "false"
            columns = signed_columns(crystal, mask, field)
            blocks = list(blocks_from_columns(columns))
            chunks = []
            for block in blocks:
                if not chunks or len(block[0]) >= 8 or len(chunks[-1][0][0]) >= 8 or len(chunks[-1]) == 6:
                    chunks.append([])
                chunks[-1].append(block)
            chunk_names = [f"{name}Part{j}" for j in range(len(chunks))]
            for chunk_name, chunk in zip(chunk_names, chunks, strict=True):
                if len(chunk[0][0]) >= 8:
                    lines += [f"def {chunk_name}Block : Block :=", lean_block(*chunk[0]),
                              f"def {chunk_name} : List Block := [{chunk_name}Block]"]
                else:
                    lines += [f"def {chunk_name} : List Block := [",
                              ",\n".join(lean_block(*b) for b in chunk) + "]"]
            lines += [f"def {name} : List Block := " + " ++ ".join(chunk_names),
                      f"theorem {name}Valid : ∀ b ∈ {name}, blockValid {mask} {flag} b := by",
                      "  decide +kernel",
                      f"theorem {name}Coverage : coverage {name} := by decide +kernel"]
            norm = max(sum(abs(value) for _, value in column) for column in columns)
            lines += [f"theorem {name}Norm : ∀ a : State,",
                      f"    ((column {mask} {flag} a).map fun (_, v) => (|v| : ℤ)).sum ≤ {norm} := by",
                      "  decide +kernel"]
            for i, (divisor, degree) in enumerate(TEMPERATURES if mask == 0 else ((8, 90), (20, 50))):
                subtotals = []
                checks = []
                for chunk_name, chunk in zip(chunk_names, chunks, strict=True):
                    checkpoints = ([[] for _ in chunk[0][0]] if mask != 0 and len(chunk[0][0]) >= 12 else None)
                    diagonals = [list(taylor_diagonal(col, divisor, degree, checkpoints))
                                 for _, col in chunk]
                    subtotal = sum(map(sum, diagonals))
                    subtotals.append(subtotal)
                    check = f"{chunk_name}Trace{i}"
                    checks.append(check)
                    if len(chunk[0][0]) < 8:
                        lines += [f"theorem {check} : total {chunk_name} {divisor} {degree} = {subtotal} := by",
                                  "  decide +kernel"]
                        continue
                    block = f"{chunk_name}Block"
                    roots = []
                    for root, value in enumerate(diagonals[0]):
                        root_name = f"{check}Root{root}"
                        term = f"(moments {block} {divisor} {root} {degree}).2.1"
                        roots.append(root_name)
                        lines.append(f"theorem {root_name} : {term} = {value} := by")
                        if checkpoints is None:
                            lines.append("  decide +kernel")
                            continue
                        offset = 0
                        prev = None
                        for k, vector, acc, scale in checkpoints[root]:
                            literal = f"({lean_list(vector)}, {acc}, {scale})"
                            lines.append(f"  have step{k} : moments {block} {divisor} {root} {k} = {literal} := by")
                            if prev is None:
                                lines.append("    decide +kernel")
                            else:
                                advance = f"advance {block} {divisor} {root} {offset} {k-offset}"
                                lines += ["    calc",
                                          f"      moments {block} {divisor} {root} {k} =",
                                          f"          {advance} (moments {block} {divisor} {root} {offset}) :=",
                                          f"        moments_checkpoint {block} {divisor} {root} {offset} {k-offset}",
                                          f"      _ = {advance} {prev} := congrArg _ step{offset}",
                                          "      _ = _ := by decide +kernel"]
                            offset, prev = k, literal
                        advance = f"advance {block} {divisor} {root} {offset} {degree-offset}"
                        lines += ["  calc",
                                  f"    {term} =",
                                  f"        ({advance} (moments {block} {divisor} {root} {offset})).2.1 :=",
                                  f"      congrArg (fun x => x.2.1) (moments_checkpoint {block} {divisor} {root} {offset} {degree-offset})",
                                  f"    _ = ({advance} {prev}).2.1 := congrArg (fun x => ({advance} x).2.1) step{offset}",
                                  "    _ = _ := by decide +kernel"]
                    indices = lean_list(range(len(diagonals[0])))
                    values = lean_list(diagonals[0])
                    if mask == 0:
                        lines += [f"theorem {check} : total {chunk_name} {divisor} {degree} = {subtotal} := by",
                                  f"  have hr : List.range {block}.states.length = {indices} := by decide +kernel",
                                  f"  simp only [total, {chunk_name}, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, add_zero]",
                                  "  unfold numerator",
                                  "  rw [hr]",
                                  "  simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, " +
                                  ", ".join(roots) + "]",
                                  "  decide +kernel"]
                        continue
                    list_proof = "List.Forall₂.nil"
                    for root_name in reversed(roots):
                        list_proof = f"List.Forall₂.cons {root_name} ({list_proof})"
                    lines += [f"theorem {check} : total {chunk_name} {divisor} {degree} = {subtotal} := by",
                              f"  exact singleton_trace {block} {divisor} {degree} {indices} {values} _",
                              "    (by decide +kernel)",
                              f"    ({list_proof})",
                              "    (by decide +kernel)"]
                lines += [f"def {name}Trace{i} : ℤ := {sum(subtotals)}",
                          f"theorem {name}Trace{i}Correct : total {name} {divisor} {degree} = {name}Trace{i} := by",
                          f"  simp only [{name}, total_append, " + ", ".join(checks) + "]",
                          f"  decide +kernel"]
                bound = (norm + divisor - 1) // divisor
                center = f"traceCenter {name}Trace{i} {divisor} {degree}"
                error = f"traceError {bound} {degree}"
                lines += [f"def {name}Partition{i}Lo : ℚ := {center} - {error}",
                          f"def {name}Partition{i}Hi : ℚ := {center} + {error}",
                          f"theorem {name}Partition{i} : ({name}Partition{i}Lo : ℝ) ≤",
                          f"    ThermalTrace.partition (hamiltonian {mask} {flag} {divisor}) ∧",
                          f"    ThermalTrace.partition (hamiltonian {mask} {flag} {divisor}) ≤",
                          f"      ({name}Partition{i}Hi : ℝ) := by",
                          f"  exact partition_checked {mask} {flag} {name} {name}Valid {name}Coverage",
                          f"    {divisor} (by decide) {degree} {bound} (by decide)",
                          f"    (fun a => ({name}Norm a).trans (by decide)) _ {name}Trace{i}Correct"]
                response_data[i][field] = free_energy(trace_bounds(matrix_from_columns(columns),
                                                                   Fraction(divisor, 40)),
                                                       Fraction(divisor, 40))
            lines.append("")
        for i, ((divisor, _), (zero, sourced)) in enumerate(zip(TEMPERATURES, response_data, strict=True)):
            lo, hi = difference(zero, sourced, Fraction(1, 200))
            lower = lo * RESPONSE_GRID // 1
            upper = -(-hi * RESPONSE_GRID // 1)
            lines.extend([f"def m{mask}Response{i}Lo : ℚ := {lower} / {RESPONSE_GRID}",
                          f"def m{mask}Response{i}Hi : ℚ := {upper} / {RESPONSE_GRID}",
                          f"theorem m{mask}Response{i} : (m{mask}Response{i}Lo : ℝ) ≤",
                          f"    benchmarkResponse {mask} {divisor} ∧",
                          f"    benchmarkResponse {mask} {divisor} ≤ (m{mask}Response{i}Hi : ℝ) := by",
                          f"  exact response_checked {mask} {divisor} (by decide) _ _ _ _ _ _",
                          f"    m{mask}h0Partition{i} m{mask}h1Partition{i} (by decide +kernel)"])
        lines.append("")
        yield mask, "\n".join(lines + ["end Grain.HubbardChannels", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the retained Lean witnesses")
    args = parser.parse_args()
    directory = ROOT / "Grain/HubbardData"
    if not args.check:
        directory.mkdir(exist_ok=True)
    crystal = read_crystal(ROOT / "artifacts/crystal_bcs_example.json")
    for mask, source in lean_sources(crystal):
        target = directory / f"Mask{mask}.lean"
        if args.check:
            if target.read_text() != source:
                parser.exit(1, f"Hubbard channel witnesses differ in {target.name}\n")
        else:
            target.write_text(source)
    if args.check:
        print("Hubbard channel witnesses reproduced")


if __name__ == "__main__":
    main()
