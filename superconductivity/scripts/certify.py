#!/usr/bin/env python3
"""Generate full-Hamiltonian witnesses using exact rational linear algebra."""
import argparse
from fractions import Fraction
from itertools import product
import json

from provenance import ARTIFACTS, CANDIDATES, verify_prediction

GRID = 10**8
WEIGHT_SCALE = 10**24


def occupation_basis(orbitals, electrons):
    return sorted(
        (c for c in product(range(3), repeat=orbitals) if sum(c) == electrons),
        key=lambda c: tuple(reversed(c)),
    )


def hamiltonian(levels, coupling, electrons):
    states = occupation_basis(len(levels), electrons)
    index = {c: i for i, c in enumerate(states)}
    matrix = [[0] * len(states) for _ in states]
    for i, c in enumerate(states):
        matrix[i][i] = sum(e * k for e, k in zip(levels, c)) - coupling * c.count(2)
        for source, occupation in enumerate(c):
            if occupation == 2:
                for destination, vacancy in enumerate(c):
                    if vacancy == 0:
                        moved = list(c)
                        moved[source], moved[destination] = 0, 2
                        matrix[i][index[tuple(moved)]] = -coupling
    return matrix


def components(matrix):
    remaining = set(range(len(matrix)))
    while remaining:
        queue = [min(remaining)]
        remaining.remove(queue[0])
        for i in queue:
            neighbors = [j for j in sorted(remaining) if matrix[i][j]]
            remaining.difference_update(neighbors)
            queue.extend(neighbors)
        yield sorted(queue)


def factor(matrix, shift):
    """Return unit lower triangular L and positive D for A - shift = LDLᵀ."""
    n = len(matrix)
    lower = [[Fraction(int(i == j)) for j in range(n)] for i in range(n)]
    diagonal = []
    for j in range(n):
        pivot = matrix[j][j] - shift - sum(lower[j][k] ** 2 * diagonal[k] for k in range(j))
        if pivot <= 0:
            return None
        diagonal.append(pivot)
        for i in range(j + 1, n):
            lower[i][j] = (
                matrix[i][j] - sum(lower[i][k] * lower[j][k] * diagonal[k] for k in range(j))
            ) / pivot
    return lower, diagonal


def solve_ones(lower, diagonal):
    forward = []
    for i, row in enumerate(lower):
        forward.append(1 - sum(row[j] * value for j, value in enumerate(forward)))
    weights = [Fraction(0)] * len(diagonal)
    for i in reversed(range(len(weights))):
        weights[i] = forward[i] / diagonal[i] - sum(
            lower[j][i] * weights[j] for j in range(i + 1, len(weights))
        )
    return weights


def matvec(matrix, vector):
    return [sum(a * x for a, x in zip(row, vector)) for row in matrix]


def certify(matrix):
    blocks = [(indices, [[matrix[i][j] for j in indices] for i in indices])
              for indices in components(matrix)]
    left = (min(map(sum, matrix)) - 1) * GRID
    right = min(row[i] for i, row in enumerate(matrix)) * GRID
    while right - left > 1:
        middle = (left + right) // 2
        if all(factor(block, Fraction(middle, GRID)) is not None for _, block in blocks):
            left = middle
        else:
            right = middle
    lo, hi = Fraction(left - 1, GRID), Fraction(right + 1, GRID)
    lower = [0] * len(matrix)
    best = None
    for indices, block in blocks:
        if lo <= min(map(sum, block)):
            weights = [1] * len(block)
        else:
            exact = solve_ones(*factor(block, lo))
            weights = [round(WEIGHT_SCALE * value / max(exact)) for value in exact]
        for i, weight in zip(indices, weights):
            lower[i] = weight
        numerator = sum(x * y for x, y in zip(weights, matvec(block, weights)))
        ratio = Fraction(numerator, sum(x * x for x in weights))
        if best is None or ratio < best[0]:
            trial = [0] * len(matrix)
            for i, weight in zip(indices, weights):
                trial[i] = weight
            best = ratio, trial
    if any(x <= 0 or ax < lo * x for x, ax in zip(lower, matvec(matrix, lower))) or best[0] > hi:
        raise ArithmeticError("exact witness check failed")
    return {"lo": str(lo), "hi": str(hi), "lower": lower, "trial": best[1]}


def make_data():
    design = json.loads((ARTIFACTS / "design.json").read_text())
    return {
        name: {
            "spectrum": levels,
            "sectors": {
                str(n): certify(hamiltonian(levels, design["coupling"], n))
                for n in design["electron_numbers"]
            },
        }
        for name, levels in design["spectra"].items()
    }


def lean_array(values):
    # Wrap long integer vectors to keep witness data readable.
    groups = [", ".join(map(str, values[i:i + 6])) for i in range(0, len(values), 6)]
    return "#[" + ",\n      ".join(groups) + "]"


def make_lean(data):
    result = [
        "/- Generated by scripts/certify.py from the full occupation Hamiltonians. -/",
        "import Grain.Certify", "", "namespace Grain.Certificate", "",
    ]
    for name, case in data.items():
        result += [f"def {name}Spectrum : Fin 5 → ℤ := !{case['spectrum']}", ""]
        for n, values in case["sectors"].items():
            result += [
                f"def {name}{n} : Witness {n} where",
                f"  lo := {values['lo']}", f"  hi := {values['hi']}",
                f"  lower i := ({lean_array(values['lower'])} : Array ℚ)[i.val]!",
                f"  trial i := ({lean_array(values['trial'])} : Array ℚ)[i.val]!",
                "",
                "set_option maxRecDepth 10000 in", "set_option maxHeartbeats 0 in",
                f"theorem {name}{n}_valid : {name}{n}.Valid {name}Spectrum := by decide +kernel",
                "",
            ]
    return "\n".join(result + ["end Grain.Certificate", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="reproduce without writing files")
    args = parser.parse_args()
    verify_prediction()
    if not args.check and any(path.exists() for path in CANDIDATES):
        raise ValueError("existing experiment artifacts are immutable")
    data = make_data()
    contents = (json.dumps(data, indent=2) + "\n", make_lean(data))
    for path, content in zip(CANDIDATES, contents):
        if args.check:
            if path.read_text() != content:
                raise ValueError(f"regeneration mismatch for {path.name}")
        else:
            with path.open("x") as output:
                output.write(content)
    print("Full-Hamiltonian certificates reproduced" if args.check else "Full-Hamiltonian certificates generated")


if __name__ == "__main__":
    main()
