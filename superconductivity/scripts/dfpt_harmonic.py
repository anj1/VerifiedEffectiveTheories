#!/usr/bin/env python3
"""Emit a Lean reconstruction of a single real spin-degenerate DFPT band."""
import argparse
from fractions import Fraction
import json
from pathlib import Path

from dfpt_shell_eft import parse_case
from pairing import lean_rat, lean_vec


def lean_string(value):
    if any(ord(char) < 32 for char in value):
        codes = ", ".join(str(ord(char)) for char in value)
        return f"String.ofList ([{codes}].map Char.ofNat)"
    return json.dumps(value, ensure_ascii=False)


def input_source(raw):
    case = parse_case(raw)
    convention = raw["screening_convention"]
    if not isinstance(convention, str) or not convention.strip():
        raise ValueError("screening_convention must describe the supplied screened interaction")

    def spin(slot):
        orbital, spin_index = slot
        return f"({orbital}, {spin_index})"

    def pair(slots):
        return f"({spin(slots[0])}, {spin(slots[1])})"

    def derivative(entries):
        return "[" + ", ".join(
            f"({i}, {j}, {lean_rat(entries[i, j])})" for i, j in sorted(entries)
        ) + "]"

    density = ", ".join(
        f"⟨{spin(a)}, {spin(b)}, {lean_rat(value)}⟩" for a, b, value in case.density
    )
    scattering = ", ".join(
        f"⟨{pair(create)}, {pair(annihilate)}, {lean_rat(value)}⟩"
        for create, annihilate, value in case.scattering
    )
    if case.cartesian is None:
        vertices = lean_vec(f".projected {derivative(mode)}" for _, mode in case.modes)
    else:
        vertices = lean_vec(f".cartesian {lean_vec(map(lean_rat, mode))}" for _, mode in case.modes)
    cartesian = case.cartesian or ()
    return f"""def input : Input {len(case.levels)} {len(cartesian)} {len(case.modes)} where
  levels := {lean_vec(map(lean_rat, case.levels))}
  density := [{density}]
  scattering := [{scattering}]
  screeningConvention := {lean_string(convention)}
  cartesian := {lean_vec(map(derivative, cartesian))}
  force := {lean_vec(lean_rat(force) for force, _ in case.modes)}
  vertex := {vertices}

def upstreamSectorError : ℚ := {lean_rat(case.upstream)}
"""

def lean_source(raw):
    case = parse_case(raw)
    return f"""import Grain.HarmonicBand

/- This file is generated by scripts/dfpt_harmonic.py from a primitive DFPT case. -/

namespace Grain.HarmonicBand.Export

{input_source(raw)}
set_option maxRecDepth 10000 in
set_option maxHeartbeats 0 in
theorem input_valid : Valid input := by decide +kernel

theorem certified_harmonic_lower {{cutoff : ℕ}}
    (ψ : Quanta {len(case.modes)} cutoff → State {len(case.levels)} → ℝ) :
    (∑ q, Grain.form (instantaneous input) (ψ q)) ≤ harmonicForm input ψ :=
  harmonic_lower input input_valid ψ

end Grain.HarmonicBand.Export
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="DFPT case or shell experiment JSON")
    parser.add_argument("--case", help="case name in a shell experiment export")
    args = parser.parse_args()
    try:
        raw = json.loads(args.input.read_text(), parse_float=Fraction)
        if "cases" in raw:
            if args.case is None:
                raise ValueError("select a case with --case")
            raw = raw["cases"][args.case]
        elif args.case is not None:
            raise ValueError("--case requires a shell experiment JSON")
        print(lean_source(raw), end="")
    except (KeyError, TypeError, ValueError, OSError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
